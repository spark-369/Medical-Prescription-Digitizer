"use client";

import { useEffect, useTransition } from "react";
import { useRouter } from "next/navigation";
import { BarChart3, Lightbulb, Loader2, Sparkles, Trash2 } from "lucide-react";
import { toast } from "sonner";

import { deleteReportAction, generateReportAction } from "@/actions/reports";
import { Alert, AlertDescription, AlertTitle } from "@/components/ui/alert";
import { Button } from "@/components/ui/button";
import {
  Card,
  CardContent,
  CardDescription,
  CardHeader,
  CardTitle,
} from "@/components/ui/card";
import { ConfirmDialog } from "@/components/confirm-dialog";
import type { AiReport } from "@/lib/api/types";
import { formatDate } from "@/lib/utils";

const DISCLAIMER =
  "AI-generated analysis — informational only. Base clinical decisions on professional judgment.";

export function ReportsView({ initial }: { initial: AiReport[] }) {
  const router = useRouter();
  const reports = initial;
  const [isPending, startTransition] = useTransition();

  const anyPending = reports.some((report) => report.status === "pending");

  // Poll while any report is being generated.
  useEffect(() => {
    if (!anyPending) return;
    const interval = setInterval(() => router.refresh(), 4000);
    return () => clearInterval(interval);
  }, [anyPending, router]);

  const onGenerate = () => {
    startTransition(async () => {
      const result = await generateReportAction();
      if (!result.ok) {
        toast.error(result.error ?? "Could not start the report.");
        return;
      }
      toast.info("Report generation started");
      router.refresh();
    });
  };

  const onDelete = (id: string) => {
    startTransition(async () => {
      const result = await deleteReportAction(id);
      if (!result.ok) {
        toast.error(result.error ?? "Delete failed.");
        return;
      }
      toast.success("Report deleted");
      router.refresh();
    });
  };

  return (
    <div className="space-y-6">
      <div className="flex flex-wrap items-center justify-between gap-4">
        <div>
          <h1 className="text-2xl font-semibold tracking-tight">AI reports</h1>
          <p className="text-muted-foreground text-sm">
            Analytics over your prescription history, generated by the local
            model.
          </p>
        </div>
        <Button onClick={onGenerate} disabled={isPending || anyPending}>
          {isPending || anyPending ? (
            <Loader2 className="animate-spin" />
          ) : (
            <Sparkles />
          )}
          Generate report
        </Button>
      </div>

      {reports.length === 0 && (
        <Card>
          <CardContent className="flex flex-col items-center gap-3 py-16 text-center">
            <div className="bg-muted flex size-12 items-center justify-center rounded-full">
              <BarChart3 className="text-muted-foreground size-6" />
            </div>
            <p className="font-medium">No reports yet</p>
            <p className="text-muted-foreground max-w-md text-sm">
              Generate your first report to see prescribing patterns, top
              medications and actionable recommendations.
            </p>
          </CardContent>
        </Card>
      )}

      <div className="space-y-4">
        {reports.map((report) => (
          <Card key={report.id}>
            {report.status === "pending" && (
              <CardContent className="flex items-center gap-3 py-10 text-sm">
                <Loader2 className="size-4 animate-spin" />
                Analyzing your prescription history…
              </CardContent>
            )}

            {report.status === "failed" && (
              <CardContent className="py-6">
                <Alert variant="destructive">
                  <Lightbulb className="size-4" />
                  <AlertTitle>Report generation failed</AlertTitle>
                  <AlertDescription>
                    {report.model ? "Try generating a new report." : "See server logs."}
                  </AlertDescription>
                </Alert>
              </CardContent>
            )}

            {report.status === "ready" && report.content && (
              <>
                <CardHeader>
                  <div className="flex items-start justify-between gap-4">
                    <div>
                      <CardTitle className="flex items-center gap-2">
                        <Sparkles className="size-4" />
                        {report.content.headline}
                      </CardTitle>
                      <CardDescription>
                        {formatDate(report.created_at)}
                      </CardDescription>
                    </div>
                    <ConfirmDialog
                      destructive
                      trigger={
                        <Button
                          variant="ghost"
                          size="icon"
                          className="text-muted-foreground hover:text-destructive"
                          aria-label="Delete report"
                        >
                          <Trash2 className="size-4" />
                        </Button>
                      }
                      title="Delete this report?"
                      description="The generated report will be permanently removed."
                      confirmLabel="Delete"
                      onConfirm={() => onDelete(report.id)}
                    />
                  </div>
                </CardHeader>
                <CardContent className="space-y-4">
                  <p className="text-sm leading-relaxed">
                    {report.content.overview}
                  </p>

                  {report.content.highlights.length > 0 && (
                    <div className="grid gap-3 sm:grid-cols-2">
                      {report.content.highlights.map((highlight, index) => (
                        <div
                          key={index}
                          className="bg-muted/50 rounded-lg border p-3"
                        >
                          <p className="flex items-center gap-2 text-sm font-semibold">
                            <Lightbulb className="text-primary size-4 shrink-0" />
                            {highlight.title}
                          </p>
                          <p className="text-muted-foreground mt-1 text-sm">
                            {highlight.detail}
                          </p>
                        </div>
                      ))}
                    </div>
                  )}

                  {report.content.recommendations.length > 0 && (
                    <div>
                      <p className="text-sm font-semibold">Recommendations</p>
                      <ul className="mt-2 space-y-1.5">
                        {report.content.recommendations.map(
                          (recommendation, index) => (
                            <li
                              key={index}
                              className="text-muted-foreground flex items-start gap-2 text-sm"
                            >
                              <span className="text-primary mt-0.5">•</span>
                              {recommendation}
                            </li>
                          ),
                        )}
                      </ul>
                    </div>
                  )}

                  <p className="text-muted-foreground text-xs">{DISCLAIMER}</p>
                </CardContent>
              </>
            )}
          </Card>
        ))}
      </div>
    </div>
  );
}
